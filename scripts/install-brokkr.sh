#!/usr/bin/env bash
# Install the Brokkr Flash AppImage for the current user, plus a wrapper that
# uses XWayland on Wayland sessions. No root required.
#
# Override the destinations with APPDIR=/some/dir or BINDIR=/some/dir.

set -euo pipefail

APPDIR="${APPDIR:-$HOME/Applications}"
BINDIR="${BINDIR:-$HOME/.local/bin}"
DESKTOP_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
mkdir -p "$APPDIR" "$BINDIR" "$DESKTOP_DIR"

case "$(uname -m)" in
  x86_64)  pattern='linux-x86_64\.AppImage' ;;
  aarch64) pattern='linux-arm64\.AppImage' ;;
  *) printf 'error: unsupported architecture: %s\n' "$(uname -m)" >&2; exit 1 ;;
esac

api="https://api.github.com/repos/Gabriel2392/brokkr-flash/releases/latest"
url="$(curl -fsSL --retry 3 --connect-timeout 15 "$api" \
  | grep -oE "https://[^\"]*${pattern}" | head -n1)"

if [[ -z $url ]]; then
  printf 'error: could not find a Linux AppImage in the latest Brokkr release\n' >&2
  exit 1
fi

tmp="$APPDIR/.Brokkr.AppImage.$$"
trap 'rm -f "$tmp"' EXIT

printf 'Downloading Brokkr (%s)\n' "${url##*/}"
curl -fsSL --retry 3 --retry-delay 2 --connect-timeout 15 --max-time 600 \
  -o "$tmp" "$url"

chmod 0755 "$tmp"
mv -f "$tmp" "$APPDIR/Brokkr.AppImage"

cat > "$BINDIR/brokkr-flash" <<EOF
#!/bin/sh
# Generated by arch-labwc-noctalia/scripts/install-brokkr.sh
export QT_QPA_PLATFORM="\${QT_QPA_PLATFORM:-xcb}"
exec "$APPDIR/Brokkr.AppImage" "\$@"
EOF
chmod 0755 "$BINDIR/brokkr-flash"

cat > "$DESKTOP_DIR/brokkr-flash.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=Brokkr Flash
Comment=Samsung device flashing utility (Odin alternative)
Exec=$BINDIR/brokkr-flash
Icon=phone
Terminal=false
Categories=Utility;
Keywords=samsung;odin;flash;firmware;
EOF
chmod 0644 "$DESKTOP_DIR/brokkr-flash.desktop"

if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "$DESKTOP_DIR" >/dev/null 2>&1 || true
fi

printf 'Installed Brokkr to %s\n' "$APPDIR/Brokkr.AppImage"
printf 'Run: brokkr-flash   (also in the launcher)\n'
